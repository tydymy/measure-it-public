"""Appelman et al. 2024 (Nat Commun 15:17) Source Data: Long COVID vs healthy, PEM induction, metabolomics.

Registers the source `appelman_lc_pem_source` (download via `measure_it.download`, MANIFEST.json, DATA_AUDIT.md,
registry_entry.yaml) and exposes `load_*` readers used by `measure_it.labs.appelman_metabolomics`. Every count in the
audit is computed from the file. Group-by-outcome statistics are NOT computed here (they belong to the locked
analysis plan docs/ANALYSIS_PLAN_LABS_VS_DIAGNOSIS.md).

    uv run python -m measure_it.ingestion.appelman_lc_pem
"""
from __future__ import annotations

import hashlib
import json

import pandas as pd

from ..config import raw_dir, utc_now_iso
from ..download import download_file, load_manifest
from ..registry import write_registry_entry

SOURCE_ID = "appelman_lc_pem_source"
URL = ("https://static-content.springer.com/esm/art%3A10.1038%2Fs41467-023-44432-3/MediaObjects/"
       "41467_2023_44432_MOESM4_ESM.xlsx")
FILENAME = "41467_2023_44432_MOESM4_ESM.xlsx"
DOI = "10.1038/s41467-023-44432-3"
SHEET_BLOOD = "Supplementary Data Figure 6B"
SHEET_MUSCLE = "Supplementary Data Figure 6A"
SHEET_DOMAIN_BLOOD = "Supp. Fig 6B - Domain blood"
SHEET_DOMAIN_MUSCLE = "Supp. Fig 6A - Domain Muscle"
SHEET_DEMOG = "Table 1"
SHEET_VO2 = "Figure1"
GROUPS = {"Long COVID": 1, "Healthy": 0}
META_COLS = ("ID", "Group", "Time")


def fetch() -> "Path":  # noqa: F821
    return download_file(URL, SOURCE_ID, FILENAME, min_bytes=100_000)


def path():
    return raw_dir(SOURCE_ID) / FILENAME


def load_metabolomics(tissue: str) -> tuple[pd.DataFrame, list[str]]:
    """Long table (ID, Group, Time, <metabolites>) exactly as released; tissue in {'blood', 'muscle'}."""
    sheet = SHEET_BLOOD if tissue == "blood" else SHEET_MUSCLE
    d = pd.read_excel(path(), sheet_name=sheet)
    mets = [c for c in d.columns if c not in META_COLS]
    d["ID"] = d["ID"].astype(int)
    return d, mets


def load_domains(tissue: str) -> pd.DataFrame:
    sheet = SHEET_DOMAIN_BLOOD if tissue == "blood" else SHEET_DOMAIN_MUSCLE
    return pd.read_excel(path(), sheet_name=sheet).dropna(subset=["Metabolite"])


def load_demographics() -> pd.DataFrame:
    t = pd.read_excel(path(), sheet_name=SHEET_DEMOG)
    t = t.rename(columns={c: "age_not_released" for c in t.columns if str(c).startswith("age")})
    t["ID"] = t["ID"].astype(int)
    t["female"] = (t["sex"] == "Female").astype(float)
    t["long_covid"] = t["Group"].map(GROUPS)
    return t


def load_vo2() -> pd.DataFrame:
    f = pd.read_excel(path(), sheet_name=SHEET_VO2)
    f = f.rename(columns={c: "age_not_released" for c in f.columns if str(c).startswith("age")})
    f["ID"] = f["ID"].astype(int)
    return f[["ID", "VO2max", "peakpoweroutput", "GET"]]


def _counts() -> dict:
    demo = load_demographics()
    out = {"table1_people": int(len(demo)),
           "table1_by_group_sex": {g: {s: int(n) for s, n in x["sex"].value_counts().items()}
                                   for g, x in demo.groupby("Group")},
           "bmi_nonmissing": int(demo["bmi"].notna().sum()),
           "age_released": bool(demo["age_not_released"].notna().any())}
    for tissue in ("blood", "muscle"):
        d, mets = load_metabolomics(tissue)
        out[f"{tissue}_metabolites"] = len(mets)
        out[f"{tissue}_rows"] = int(len(d))
        out[f"{tissue}_group_time"] = {f"{g}|{t}": int(n) for (g, t), n in d.groupby(["Group", "Time"]).size().items()}
        out[f"{tissue}_missing_cells"] = int(d[mets].isna().sum().sum())
        out[f"{tissue}_nonpositive_cells"] = int((d[mets] <= 0).sum().sum())
        out[f"{tissue}_baseline_ids"] = int(d.loc[d["Time"] == "Baseline", "ID"].nunique())
    vo2 = load_vo2()
    b, _ = load_metabolomics("blood")
    m, _ = load_metabolomics("muscle")
    bb = set(b.loc[b["Time"] == "Baseline", "ID"])
    mb = set(m.loc[m["Time"] == "Baseline", "ID"])
    v = set(vo2.loc[vo2["VO2max"].notna(), "ID"])
    grp = demo.set_index("ID")["Group"]
    out["overlap"] = {name: {g: int(sum(grp.get(i) == g for i in ids)) for g in GROUPS}
                      for name, ids in (("baseline_blood", bb), ("baseline_muscle", mb), ("vo2max", v),
                                        ("blood_and_muscle", bb & mb), ("vo2max_and_blood", v & bb),
                                        ("vo2max_and_muscle", v & mb))}
    out["ids_not_in_table1"] = sorted(int(i) for i in (bb | mb | v) - set(grp.index))
    return out


