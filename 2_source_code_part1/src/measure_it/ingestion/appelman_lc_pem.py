def run() -> dict:
    p = fetch()
    man = load_manifest(SOURCE_ID)
    f = man["files"][FILENAME]
    assert hashlib.sha256(p.read_bytes()).hexdigest() == f["sha256"]
    c = _counts()
    write_audit(c, man)
    ov = c["overlap"]
    write_registry_entry({
        "source_id": SOURCE_ID,
        "name": "Appelman et al. 2024 Long COVID PEM study Source Data (plasma + muscle metabolomics, VO2max; "
                "Nat Commun 15:17)",
        "publisher": "Springer Nature / Nature Communications (authors: Amsterdam UMC, Vrije Universiteit Amsterdam)",
        "landing_url": f"https://doi.org/{DOI}",
        "access_urls": [URL],
        "license": "CC BY 4.0 (article and supplementary Source Data)",
        "access_conditions": "Open anonymous download; no registration or DUA (verified 2026-09-24).",
        "retrieved_at": f["retrieved_at"],
        "source_version": f"Source Data file {FILENAME} (HTTP Last-Modified {f.get('last_modified', '')}); "
                          f"sha256 {f['sha256']}",
        "update_date": "2024-01-04 (article publication; static)",
        "data_layer": "person",
        "unit_of_observation": "person x timepoint (baseline, 1 day and 1 week after PEM induction)",
        "sample_size": {
            "people_table1": c["table1_people"],
            "baseline_blood_long_covid": ov["baseline_blood"]["Long COVID"],
            "baseline_blood_healthy": ov["baseline_blood"]["Healthy"],
            "baseline_muscle_long_covid": ov["baseline_muscle"]["Long COVID"],
            "baseline_muscle_healthy": ov["baseline_muscle"]["Healthy"],
            "blood_metabolites": c["blood_metabolites"], "muscle_metabolites": c["muscle_metabolites"],
        },
        "geographic_resolution": "none",
        "person_level": True, "geographic": False, "omics": True, "wearable": False,
        "participant_linkage": "metabolomics (blood, muscle), Table 1 demographics and Figure1 VO2max share the "
                               "study ID within the file; no key to Charlton 2026 or other datasets",
        "true_participant_linkage_across_modalities": True,
        "status": "ingested",
        "processed_outputs": ["phenotype_signatures__appelman_metabolomics",
                              "results/tables/labs_dx_appelman_*.csv"],
        "audit": f"data/raw/{SOURCE_ID}/DATA_AUDIT.md",
        "ingestion_module": "measure_it.ingestion.appelman_lc_pem",
        "limitations": ["46 people; healthy controls only; no ME/CFS group in this file",
                        "age not released (sex and BMI only)",
                        "same trial as Charlton 2026 (NCT05225688): not independent evidence",
                        "relative, normalised intensities after the authors' QC"],
        "notes": "Appelman B, Charlton BT, Goulding RP, et al. Muscle abnormalities worsen after post-exertional "
                 "malaise in long COVID. Nat Commun 15, 17 (2024). doi:10.1038/s41467-023-44432-3 (PMC10766651). "
                 "Analysis: measure_it.labs.appelman_metabolomics under docs/ANALYSIS_PLAN_LABS_VS_DIAGNOSIS.md.",
    })
    return c


if __name__ == "__main__":
    print(json.dumps(run(), indent=2, default=str))
